export interface Demo {
  /** Unique demo ID, matches the route segment under /demos/ */
  id: string;
  /** Display title */
  title: string;
  /** Short description of the technique */
  description: string;
  /** Lucide icon component */
  icon: LucideIcon;
  /** Readiness status */
  status: "ready" | "coming" | "wip";
  /** Feature bullet points */
  features: string[];
  /** Story reference (research sprint) */
  story: string;
  /** Parent lab slug (matches lab.slug) */
  labSlug: string;
  /** Parent lab owner username (matches lab.owner.username) */
  labOwner: string;
}

/**
 * Lab metadata for display in demo pages.
 * Maps labSlug to lab display info.
 */
export interface LabRef {
  slug: string;
  owner: string;
  name: string;
  path: string;
}

