/**
 * Get demos for a specific lab by slug.
 */
export function getDemosForLab(labSlug: string): Demo[] {
  return DEMOS.filter((d) => d.labSlug === labSlug);
}

/**
 * Get a single demo by ID.
 */
export function getDemoById(id: string): Demo | undefined {
  return DEMOS.find((d) => d.id === id);
}

/**
 * Get the lab reference for a demo.
 */
export function getLabRefForDemo(demo: Demo): LabRef | undefined {
  return LAB_REFS[demo.labSlug];
}

/**
 * Get the count of ready demos for a lab.
 */
export function getReadyDemoCount(labSlug: string): number {
  return getDemosForLab(labSlug).filter((d) => d.status === "ready").length;
}
