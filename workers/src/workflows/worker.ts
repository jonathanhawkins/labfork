/**
 * WorkerWorkflow executes a single task for an agent.
 *
 * This workflow is triggered by the Manager Workflow or manually via API.
 * It handles the complete lifecycle of task execution including:
 * - Loading context from the database
 * - Checking for physical barriers
 * - Planning work using AI
 * - Executing each step
 * - Logging all work
 * - Creating artifacts
 */
export class WorkerWorkflow extends WorkflowEntrypoint<Env, WorkerPayload> {
  /**
   * Main workflow execution
   */
  async run(
    event: WorkflowEvent<WorkerPayload>,
    step: WorkflowStep
  ): Promise<WorkflowResult> {
    const { taskId, agentId } = event.payload;

    console.log(`WorkerWorkflow started: task=${taskId}, agent=${agentId}`);

    // Step 1: Load context from database
    const context = await step.do('load-context', async () => {
      return await this.loadContext(taskId, agentId);
    });

    if (!context) {
      console.error(`Failed to load context for task=${taskId}, agent=${agentId}`);
      return { status: 'failed', reason: 'context_not_found', partial: false, resultsJson: null };
    }

    // Update agent status to working
    await step.do('update-agent-status', async () => {
      await this.updateAgentStatus(agentId, 'working', taskId);
      return { updated: true };
    });

    // Step 2: Check for physical barrier
    if (context.task.requires_physical === 1) {
      const blockResult = await step.do('handle-physical', async () => {
        // Create physical barrier record
        const barrier: PhysicalBarrier = {
          type: 'test', // Default type, could be determined from task description
          description: context.task.description || context.task.title,
          instructions: [
            `Complete the following physical task:`,
            context.task.title,
            context.task.description || '',
          ],
          blocking_tasks: [taskId],
        };

        // Mark task as blocked
        await this.markTaskBlocked(taskId, 'Requires physical action');

        // Notify humans
        await notifyHumans(barrier);

        // Update agent status back to idle
        await this.updateAgentStatus(agentId, 'idle', null);

        return { blocked: true, reason: 'physical_required' };
      });

      return { status: 'blocked', reason: blockResult.reason, partial: false, resultsJson: null };
    }

    // Step 3: Plan the work using AI
    const plan = await step.do('plan-work', async () => {
      return await this.planWork(context);
    });

    if (!plan || !plan.steps || plan.steps.length === 0) {
      console.error(`Failed to create execution plan for task=${taskId}`);
      return { status: 'failed', reason: 'planning_failed', partial: false, resultsJson: null };
    }

    console.log(
      `Execution plan created with ${plan.steps.length} steps for task=${taskId}`
    );

    // Initialize results accumulator
    const allResults: { [stepId: string]: string } = {};

    // Step 4: Execute each step in the plan
    for (let i = 0; i < plan.steps.length; i++) {
      const planStep = plan.steps[i];

      // Update task progress
      const progress = Math.round(((i + 1) / plan.steps.length) * 100);
      await step.do(`progress-${planStep.id}`, async () => {
        await this.updateTaskProgress(taskId, progress);
        return { progress };
      });

      // Execute the step
      const result = await step.do(`exec-${planStep.id}`, async () => {
        return await this.executeStep(planStep, context);
      });

      // Log the work
      await step.do(`log-${planStep.id}`, async () => {
        await this.logWork(
          agentId,
          taskId,
          planStep.action,
          JSON.stringify({ step: planStep }),
          result.output,
          result.durationMs,
          result.tokensUsed
        );
        return { logged: true };
      });

      // Store result
      allResults[planStep.id] = result.output;

      // Check if we hit a physical barrier mid-execution
      if (result.needsPhysical) {
        await step.do('mid-physical-barrier', async () => {
          // Detect and create the physical barrier
          const barrier = detectPhysicalBarrier(
            result.blockReason || planStep.description
          );

          if (barrier) {
            barrier.blocking_tasks = [taskId];
            await createHumanTask(barrier, context.projectId, this.env.DB);
            await notifyHumans(barrier);
          }

          // Mark task as blocked
          await this.markTaskBlocked(
            taskId,
            result.blockReason || 'Physical action required during execution'
          );

          // Update agent status back to idle
          await this.updateAgentStatus(agentId, 'idle', null);

          return { blocked: true };
        });

        return {
          status: 'blocked',
          reason: result.blockReason,
          partial: true,
          resultsJson: JSON.stringify(allResults),
        };
      }

      // Check if step failed
      if (!result.success) {
        console.error(`Step ${planStep.id} failed for task=${taskId}`);
        // Continue with remaining steps if possible
      }
    }

    // Step 5: Create any artifacts
    await step.do('create-artifacts', async () => {
      // Artifacts would be extracted from step results
      // For now, create a summary artifact
      await this.createArtifact(
        taskId,
        'research_note',
        `${context.task.title} - Summary`,
        JSON.stringify(allResults, null, 2)
      );
      return { created: true };
    });

    // Step 6: Complete the task
    await step.do('complete', async () => {
      // Update task status to completed
      await this.completeTask(taskId, JSON.stringify(allResults));

      // Update agent state
      await this.updateAgentStatus(agentId, 'idle', null);

      // Update agent memory with any learnings
      await this.updateAgentMemory(agentId, context);

      return { completed: true };
    });

    console.log(`WorkerWorkflow completed: task=${taskId}`);

    return { status: 'completed', reason: null, partial: false, resultsJson: JSON.stringify(allResults) };
  }

  // ==========================================================================
  // Database Operations
  // ==========================================================================

  /**
   * Loads task, agent, and project context from the database
   */
  private async loadContext(
    taskId: string,
    agentId: string
  ): Promise<SerializableContext | null> {
    try {
      // Get task
      const taskResult = await this.env.DB.prepare(
        'SELECT * FROM tasks WHERE id = ?'
      )
        .bind(taskId)
        .first<Task>();

      if (!taskResult) {
        console.error(`Task not found: ${taskId}`);
        return null;
      }

      // Get agent
      const agentResult = await this.env.DB.prepare(
        'SELECT * FROM agent_state WHERE agent_id = ?'
      )
        .bind(agentId)
        .first<AgentStateRaw>();

      if (!agentResult) {
        console.error(`Agent not found: ${agentId}`);
        return null;
      }

      // Parse JSON fields with defaults
      const persona: AgentPersona = safeParseJson<AgentPersona>(agentResult.persona) || {
        name: agentId,
        role: 'Worker',
        model: '@cf/meta/llama-3.1-70b-instruct',
        specializations: [],
        system_prompt: 'You are a helpful AI agent.',
      };

      const memory: AgentMemory = safeParseJson<AgentMemory>(agentResult.memory || '{}') || {
        context: [],
        learnings: [],
      };

      // Get project
      const projectResult = await this.env.DB.prepare(
        'SELECT id, name, slug FROM projects WHERE id = ?'
      )
        .bind(taskResult.project_id)
        .first<{ id: string; name: string; slug: string }>();

      if (!projectResult) {
        console.error(`Project not found: ${taskResult.project_id}`);
        return null;
      }

      return {
        task: taskResult,
        agentId: agentResult.agent_id,
        projectId: agentResult.project_id,
        persona,
        memory,
        projectName: projectResult.name,
        projectSlug: projectResult.slug,
      };
    } catch (error) {
      console.error('Failed to load context:', error);
      return null;
    }
  }

  /**
   * Updates the agent status and current task
   */
  private async updateAgentStatus(
    agentId: string,
    status: string,
    currentTaskId: string | null
  ): Promise<void> {
    await this.env.DB.prepare(
      `UPDATE agent_state
       SET status = ?, current_task_id = ?, last_active = datetime('now')
       WHERE agent_id = ?`
    )
      .bind(status, currentTaskId, agentId)
      .run();
  }

  /**
   * Updates the task progress percentage
   */
  private async updateTaskProgress(
    taskId: string,
    progress: number
  ): Promise<void> {
    await this.env.DB.prepare(
      `UPDATE tasks
       SET progress = ?, status = 'in_progress', updated_at = datetime('now')
       WHERE id = ?`
    )
      .bind(progress, taskId)
      .run();
  }

  /**
   * Marks a task as blocked
   */
  private async markTaskBlocked(
    taskId: string,
    reason: string
  ): Promise<void> {
    await this.env.DB.prepare(
      `UPDATE tasks
       SET status = 'blocked',
           result = ?,
           updated_at = datetime('now')
       WHERE id = ?`
    )
      .bind(JSON.stringify({ blocked_reason: reason }), taskId)
      .run();
  }

  /**
   * Marks a task as completed
   */
  private async completeTask(
    taskId: string,
    resultsJson: string
  ): Promise<void> {
    await this.env.DB.prepare(
      `UPDATE tasks
       SET status = 'completed',
           progress = 100,
           result = ?,
           updated_at = datetime('now')
       WHERE id = ?`
    )
      .bind(resultsJson, taskId)
      .run();
  }

  /**
   * Logs work to the work_log table
   */
  private async logWork(
    agentId: string,
    taskId: string,
    action: string,
    inputJson: string,
    outputJson: string,
    durationMs: number,
    tokensUsed: number
  ): Promise<void> {
    const logId = generateId('log');

    await this.env.DB.prepare(
      `INSERT INTO work_log (id, agent_id, task_id, action, input, output, duration_ms, tokens_used, created_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, datetime('now'))`
    )
      .bind(
        logId,
        agentId,
        taskId,
        action,
        inputJson,
        outputJson,
        durationMs,
        tokensUsed
      )
      .run();

    // Update agent's total tokens used
    await this.env.DB.prepare(
      `UPDATE agent_state
       SET tokens_used = tokens_used + ?
       WHERE agent_id = ?`
    )
      .bind(tokensUsed, agentId)
      .run();
  }

  /**
   * Creates an artifact in the artifacts table
   */
  private async createArtifact(
    taskId: string,
    type: string,
    name: string,
    content: string,
    metadata?: string
  ): Promise<void> {
    const artifactId = generateId('artifact');

    await this.env.DB.prepare(
      `INSERT INTO artifacts (id, task_id, type, name, content, metadata, created_at)
       VALUES (?, ?, ?, ?, ?, ?, datetime('now'))`
    )
      .bind(
        artifactId,
        taskId,
        type,
        name,
        content,
        metadata || null
      )
      .run();
  }

  /**
   * Updates agent memory with learnings from task execution
   */
  private async updateAgentMemory(
    agentId: string,
    context: SerializableContext
  ): Promise<void> {
    // Add task completion to context
    const updatedMemory: AgentMemory = {
      context: [
        ...context.memory.context.slice(-9), // Keep last 9 entries
        `Completed task: ${context.task.title}`,
      ],
      learnings: context.memory.learnings,
    };

    await this.env.DB.prepare(
      `UPDATE agent_state
       SET memory = ?, last_active = datetime('now')
       WHERE agent_id = ?`
    )
      .bind(JSON.stringify(updatedMemory), agentId)
      .run();
  }

  // ==========================================================================
  // AI Operations
  // ==========================================================================

  /**
   * Uses AI to plan the work for a task
   */
  private async planWork(context: SerializableContext): Promise<ExecutionPlan | null> {
    try {
      const prompt = fillPromptTemplate(TASK_PLANNING_PROMPT, {
        agentRole: context.persona.role,
        agentSpecializations: context.persona.specializations.join(', '),
        taskTitle: context.task.title,
        taskDescription: context.task.description || 'No description provided',
      });

      const response = await this.env.AI.run(
        '@cf/meta/llama-3.1-70b-instruct' as Parameters<Ai['run']>[0],
        {
          messages: [
            { role: 'system', content: context.persona.system_prompt },
            { role: 'user', content: prompt },
          ],
          max_tokens: 2000,
        }
      );

      // Handle response type
      const responseText =
        typeof response === 'object' && 'response' in response
          ? String((response as { response: string }).response)
          : String(response);

      const plan = safeParseJson<{
        steps: Array<{
          id: string;
          action: string;
          description: string;
          inputs?: string | object;
          expectedOutput: string;
        }>;
        estimatedDuration: string;
        physicalStepsIdentified?: string[];
      }>(responseText);

      if (!plan) {
        console.error('Failed to parse execution plan from AI response');
        // Return a default single-step plan
        return {
          steps: [
            {
              id: 'step_1',
              action: 'analyze',
              description: context.task.description || context.task.title,
              inputs: '{}',
              expectedOutput: 'Task completion',
            },
          ],
          estimatedDuration: '15 minutes',
        };
      }

      // Convert to our ExecutionPlan format with serializable inputs
      return {
        steps: plan.steps.map((s, i) => ({
          id: s.id || `step_${i + 1}`,
          action: s.action,
          description: s.description,
          inputs: typeof s.inputs === 'string' ? s.inputs : JSON.stringify(s.inputs || {}),
          expectedOutput: s.expectedOutput,
        })),
        estimatedDuration: plan.estimatedDuration,
      };
    } catch (error) {
      console.error('Failed to plan work:', error);
      return null;
    }
  }

  /**
   * Executes a single step using AI
   */
  private async executeStep(
    planStep: PlanStep,
    context: SerializableContext
  ): Promise<StepResult> {
    const startTime = Date.now();

    try {
      const prompt = fillPromptTemplate(TASK_EXECUTION_PROMPT, {
        agentRole: context.persona.role,
        agentSpecializations: context.persona.specializations.join(', '),
        taskTitle: context.task.title,
        stepDescription: planStep.description,
        stepAction: planStep.action,
        stepInputs: planStep.inputs,
        expectedOutput: planStep.expectedOutput,
        agentMemory: context.memory.learnings.slice(-5).join('\n') || 'No previous learnings',
      });

      const response = await this.env.AI.run(
        '@cf/meta/llama-3.1-70b-instruct' as Parameters<Ai['run']>[0],
        {
          messages: [
            { role: 'system', content: context.persona.system_prompt },
            { role: 'user', content: prompt },
          ],
          max_tokens: 4000,
        }
      );

      const durationMs = Date.now() - startTime;

      // Handle response type
      const responseText =
        typeof response === 'object' && 'response' in response
          ? String((response as { response: string }).response)
          : String(response);

      const result = safeParseJson<{
        success: boolean;
        output: unknown;
        artifacts?: Array<{
          type: string;
          name: string;
          content: string;
        }>;
        needsPhysical: boolean;
        blockReason?: string;
        insights?: string[];
      }>(responseText);

      if (!result) {
        // If we can't parse the result, return the raw text as output
        return {
          success: true,
          output: responseText,
          needsPhysical: false,
          blockReason: null,
          tokensUsed: estimateTokens(prompt + responseText),
          durationMs,
        };
      }

      // Check for physical barriers in the result
      const physicalCheck = detectPhysicalBarrier(
        result.blockReason || planStep.description
      );

      return {
        success: result.success,
        output: typeof result.output === 'string' ? result.output : JSON.stringify(result.output),
        needsPhysical: result.needsPhysical || physicalCheck !== null,
        blockReason: result.blockReason || null,
        tokensUsed: estimateTokens(prompt + responseText),
        durationMs,
      };
    } catch (error) {
      console.error(`Failed to execute step ${planStep.id}:`, error);
      return {
        success: false,
        output: JSON.stringify({ error: String(error) }),
        needsPhysical: false,
        blockReason: null,
        tokensUsed: 0,
        durationMs: Date.now() - startTime,
      };
    }
  }
}

// Export the workflow class
export default WorkerWorkflow;
