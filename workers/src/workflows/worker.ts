/**
 * Worker Workflow
 *
 * Executes a single task for an agent using Cloudflare Workflows.
 * This workflow handles the complete lifecycle of a task:
 * 1. Load task and agent context
 * 2. Check for physical barriers
 * 3. Plan the work using AI
 * 4. Execute each step
 * 5. Log progress and complete
 */

import { WorkflowEntrypoint, WorkflowEvent, WorkflowStep } from 'cloudflare:workers';
import {
  PhysicalBarrier,
  detectPhysicalBarrier,
  createHumanTask,
  notifyHumans,
} from '../lib/physical-barrier';

// ============================================================================
// Types
// ============================================================================

/**
 * Payload passed when triggering the workflow
 */
export interface WorkerPayload {
  taskId: string;
  agentId: string;
}

/**
 * Environment bindings for Cloudflare Workers
 */
export interface Env {
  DB: D1Database;
  AI: Ai;
}

/**
 * Task from the database
 */
interface Task {
  id: string;
  project_id: string;
  title: string;
  description: string | null;
  status: string;
  priority: number;
  assigned_agent: string | null;
  blocked_by: string | null;
  requires_physical: number; // 0 or 1 in SQLite
  progress: number;
  result: string | null;
  created_at: string;
  updated_at: string;
}

/**
 * Agent state from the database (raw JSON strings)
 */
interface AgentStateRaw {
  agent_id: string;
  project_id: string;
  persona: string; // JSON string
  memory: string | null; // JSON string
  current_task_id: string | null;
  status: string;
  tokens_used: number;
  last_active: string | null;
  created_at: string;
}

/**
 * Agent persona defining behavior and specialization
 */
interface AgentPersona {
  name: string;
  role: string;
  model: string;
  specializations: string[];
  system_prompt: string;
}

/**
 * Agent memory for context and learnings
 */
interface AgentMemory {
  context: string[];
  learnings: string[];
}

/**
 * Serializable context for workflow steps
 */
interface SerializableContext {
  task: Task;
  agentId: string;
  projectId: string;
  persona: AgentPersona;
  memory: AgentMemory;
  projectName: string;
  projectSlug: string;
}

/**
 * A single step in the execution plan
 */
interface PlanStep {
  id: string;
  action: string;
  description: string;
  inputs: string; // JSON string for serialization
  expectedOutput: string;
}

/**
 * Execution plan generated by AI (serializable)
 */
interface ExecutionPlan {
  steps: PlanStep[];
  estimatedDuration: string;
}

/**
 * Result from executing a single step (serializable)
 */
interface StepResult {
  success: boolean;
  output: string; // JSON string for serialization
  needsPhysical: boolean;
  blockReason: string | null;
  tokensUsed: number;
  durationMs: number;
}

/**
 * Final workflow result
 */
interface WorkflowResult {
  status: 'completed' | 'blocked' | 'failed';
  reason: string | null;
  partial: boolean;
  resultsJson: string | null; // JSON string for serialization
}

